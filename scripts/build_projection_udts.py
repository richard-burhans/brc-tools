def build() -> dict[str, str]:
    """filename -> file body. `.replace`, NOT `.format`: the help text is full of literal
    `{anchor}_{query}` braces -- they are the naming convention these tools exist to bridge -- and
    str.format reads every one of them as a field."""
    return {
        "anchor_grid.gxtool.yml":
            ANCHOR_GRID.replace("{script}", helper("tools/collection_anchor_grid/anchor_grid.py")),
        "phase_c2_triage.gxtool.yml":
            TRIAGE.replace("{script}", helper("tools/phase_c2_triage/phase_c2_triage.py")),
        "phase_c4_merge.gxtool.yml":
            C4_MERGE.replace("{script}", helper("tools/phase_c4_merge/phase_c4_merge.py")),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="compare against udt/ and exit non-zero if any committed copy is stale")
    args = ap.parse_args()

    stale = []
    for filename, body in build().items():
        path = UDT / filename
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != body:
                stale.append(filename)
            continue
        path.write_text(body, encoding="utf-8")
        print(f"  {'unchanged' if current == body else 'wrote':>9} udt/{filename}")

    if args.check:
        for filename in stale:
            print(f"  STALE udt/{filename}")
        if stale:
            print("  Regenerate with: python3 scripts/build_projection_udts.py")
            return 1
        print(f"  all committed projection UDTs match their helpers ({len(build())} generated)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
