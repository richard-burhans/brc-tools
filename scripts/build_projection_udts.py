#!/usr/bin/env python3
"""Generate WF-C2's User-Defined Tools by inlining the wrappers' own helper scripts.

    python3 scripts/build_projection_udts.py            # write udt/
    python3 scripts/build_projection_udts.py --check    # fail if a committed copy is stale

⛔ FIVE OF WF-C2's TWENTY-ONE STEPS NAME TOOLS usegalaxy.org DOES NOT HAVE, so the classic
workflow imports there and cannot be invoked at all: collection_self_pairs (already ported for
WF-A as `brc-self-pairs`), collection_anchor_grid, phase_c2_triage, toga2 and phase_c4_merge.
This generator emits the three that are portable.

⛔ toga2 IS NOT ONE OF THEM, AND NOT FOR WANT OF TRYING. A User-Defined Tool is a container plus a
command, so it can only wrap an image a Galaxy can PULL. tools/toga2/macros.xml records that
upstream ships only an apptainer/Singularity def -- no published Docker image, no bioconda package,
no biocontainer -- and that this project builds its own SIF onto shared storage at
/data/containers/toga2-2.0.8.sif. A local .sif path is not something usegalaxy.org can resolve.
Until an upstream image exists the TOGA2/CESAR2 rescue cannot run there by any means, which is why
workflows/align_chain_project/project_annotations_udt.gxwf.yml is the Liftoff-only pass.

⚠ THE PYTHON IS INLINED VERBATIM FROM tools/, NOT REWRITTEN. The XML wrappers read their scripts
from $__tool_directory__, which a UDT has no equivalent of, so the script travels in the command
itself -- and it travels UNCHANGED, so the two editions cannot drift into computing different
things. The one interface difference is collection_anchor_grid's: element identifiers arrive as
FILES rather than as a Cheetah-interpolated list, because a job container is handed paths and never
sees the identifiers of the collection they came from.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UDT = ROOT / "udt"

#: ⚠ Galaxy interpolates this sequence ANYWHERE in a shell_command, heredocs included, so a helper
#: carrying one -- even inside a comment or a docstring -- is rewritten on its way into the tool.
FORBIDDEN = "$("


def helper(relpath: str) -> str:
    """The wrapper's own script, indented into the heredoc, refused if it can be interpolated."""
    body = (ROOT / relpath).read_text(encoding="utf-8").rstrip("\n")
    if FORBIDDEN in body:
        sys.exit(f"REFUSING: {relpath} contains `{FORBIDDEN}`, which Galaxy would interpolate "
                 f"inside the heredoc, corrupting the inlined script.")
    return "\n".join(("  " + line).rstrip() for line in body.split("\n"))


