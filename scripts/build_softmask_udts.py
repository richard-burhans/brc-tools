def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if a committed file differs from what would be generated")
    args = ap.parse_args()

    assert_sources_aligned()
    UDT.mkdir(exist_ok=True)
    stale = []
    for fn, body in build().items():
        path = UDT / fn
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if args.check:
            if current != body:
                stale.append(fn)
            continue
        path.write_text(body, encoding="utf-8")
        print(f"  {'unchanged' if current == body else 'wrote':>9} udt/{fn}")
    if args.check:
        for fn in stale:
            print(f"  STALE udt/{fn}")
        if stale:
            print("  Regenerate with: python3 scripts/build_softmask_udts.py")
            return 1
        print("  all committed UDTs match their sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
